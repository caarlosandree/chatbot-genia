package com.chatbotgen.aplicacao.model;

/**
 * Enum que representa os roles/perfis de usuário no sistema.
 * 
 * @author Sistema
 */
public enum Role {
    /**
     * Administrador: acesso completo à plataforma, pode gerenciar todos os clientes.
     */
    ADMIN,
    
    /**
     * Cliente: acesso apenas à sua própria conta.
     */
    CLIENT
}

